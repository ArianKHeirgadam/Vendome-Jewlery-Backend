function translateText(value: string): string {
  const match = value.match(/^(\s*)(.*?)(\s*)$/s);
  if (!match) return value;
  const [, prefix, content, suffix] = match;
  const normalizedDigits = content
    .replace(/[۰-۹]/g, (digit) => String("۰۱۲۳۴۵۶۷۸۹".indexOf(digit)))
    .replace(/[٠-٩]/g, (digit) => String("٠١٢٣٤٥٦٧٨٩".indexOf(digit)));
  const exact = translations[content];
  if (exact) return `${prefix}${exact}${suffix}`;
  for (const [pattern, replacement] of dynamicTranslations) {
    if (pattern.test(content)) return `${prefix}${normalizedDigits.replace(pattern, replacement)}${suffix}`;
  }
  return normalizedDigits === content ? value : `${prefix}${normalizedDigits}${suffix}`;
}

function shouldSkip(node: Node): boolean {
  const parent = node instanceof Element ? node : node.parentElement;
  return Boolean(parent?.closest("script, style, code, pre, [data-no-translate]"));
}

function TranslationBridge({ language }: { language: AppLanguage }) {
  const originalTexts = useRef(new Map<Text, string>());
  const originalAttributes = useRef(new Map<Element, Map<string, string>>());

  useEffect(() => {
    if (language !== "en") return;
    let applying = false;
    const attributes = ["aria-label", "placeholder", "title"];

    const translateNode = (root: Node) => {
      if (shouldSkip(root)) return;
      applying = true;
      try {
        if (root.nodeType === Node.TEXT_NODE) {
          const text = root as Text;
          const translated = translateText(text.data);
          if (translated !== text.data) {
            originalTexts.current.set(text, text.data);
            text.data = translated;
          }
          return;
        }

        if (root instanceof Element) {
          for (const attribute of attributes) {
            const value = root.getAttribute(attribute);
            if (!value) continue;
            const translated = translateText(value);
            if (translated === value) continue;
            const originals = originalAttributes.current.get(root) ?? new Map<string, string>();
            originals.set(attribute, value);
            originalAttributes.current.set(root, originals);
            root.setAttribute(attribute, translated);
          }
        }

        const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
        let current = walker.nextNode();
        while (current) {
          if (!shouldSkip(current)) {
            if (current.nodeType === Node.TEXT_NODE) {
              const text = current as Text;
              const translated = translateText(text.data);
              if (translated !== text.data) {
                originalTexts.current.set(text, text.data);
                text.data = translated;
              }
            } else if (current instanceof Element) {
              for (const attribute of attributes) {
                const value = current.getAttribute(attribute);
                if (!value) continue;
                const translated = translateText(value);
                if (translated === value) continue;
                const originals = originalAttributes.current.get(current) ?? new Map<string, string>();
                originals.set(attribute, value);
                originalAttributes.current.set(current, originals);
                current.setAttribute(attribute, translated);
              }
            }
          }
          current = walker.nextNode();
        }
      } finally {
        applying = false;
      }
    };

    translateNode(document.body);
    const observer = new MutationObserver((mutations) => {
      if (applying) return;
      for (const mutation of mutations) {
        if (mutation.type === "characterData") translateNode(mutation.target);
        mutation.addedNodes.forEach(translateNode);
      }
    });
    observer.observe(document.body, { childList: true, subtree: true, characterData: true });

    return () => {
      observer.disconnect();
      applying = true;
      originalTexts.current.forEach((value, node) => {
        if (node.isConnected) node.data = value;
      });
      originalAttributes.current.forEach((values, element) => {
        if (!element.isConnected) return;
        values.forEach((value, attribute) => element.setAttribute(attribute, value));
      });
      originalTexts.current.clear();
      originalAttributes.current.clear();
      applying = false;
    };
  }, [language]);

  return null;
}

function initialLanguage(): AppLanguage {
  const language = window.localStorage.getItem(STORAGE_KEY) === "en" ? "en" : "fa";
  applyDocumentLanguage(language);
  return language;
}

function applyDocumentLanguage(language: AppLanguage) {
  document.documentElement.lang = language;
  document.documentElement.dir = language === "fa" ? "rtl" : "ltr";
  document.documentElement.dataset.locale = language;
}

export function LocaleProvider({ children }: PropsWithChildren) {
  const [language, setLanguage] = useState<AppLanguage>(initialLanguage);

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, language);
    applyDocumentLanguage(language);
  }, [language]);

  const value = useMemo<LocaleContextValue>(() => ({
    language,
    direction: language === "fa" ? "rtl" : "ltr",
    locale: language === "fa" ? "fa-IR" : "en-US",
    setLanguage: (nextLanguage) => {
      applyDocumentLanguage(nextLanguage);
      setLanguage(nextLanguage);
    },
    toggleLanguage: () => setLanguage((current) => {
      const nextLanguage = current === "fa" ? "en" : "fa";
      applyDocumentLanguage(nextLanguage);
      return nextLanguage;
    }),
  }), [language]);

  return (
    <LocaleContext.Provider value={value}>
      {children}
      <TranslationBridge language={language} />
    </LocaleContext.Provider>
  );
}

export function useLocale(): LocaleContextValue {
  const value = useContext(LocaleContext);
  if (!value) throw new Error("useLocale must be used inside LocaleProvider.");
  return value;
}
